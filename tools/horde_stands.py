# horde_stands.py (hordepub, 2026-11-09): the stand table (src/game/horde_stands.inc, docs/horde.md "Standing") from plain-game traces (HOTD_HORDE_TRACE=10
# HOTD_HORDE_FOLLOW=0:999999, --strict --default-route, arcade models): for each camera stop (HSTOP), points on the
# ground the arcade's own walkers walked while the camera was at that stop: in front of it (cos 0.6), 30-120 units away,
# past their door (8 units); one point a walker (the middle of its qualifying steps), 15 units apart, 4 a stop at most.
# usage: py -I tools/horde_stands.py out.inc plain_c1.txt plain_c2.txt ... (then keep only the rows HPLACECHECK finds clear)
import math, re, sys
out = sys.argv[1]
rows = []
for path in sys.argv[2:]:
    stops = []   # (frame, chapter, cx, cy, cz, lx, lz)
    follow = {}  # task -> [(frame, x, y, z, camx, camz, type)]
    for line in open(path, encoding='utf-8', errors='replace'):
        if line.startswith('HSTOP '):
            m = re.match(r'HSTOP (\d+) chapter (\d+) event (-?\d+) camera (\S+) (\S+) (\S+) look (\S+) (\S+)', line)
            if m:
                f, ch, ev = int(m[1]), int(m[2]), int(m[3])
                stops.append((f, ch, float(m[4]), float(m[5]), float(m[6]), float(m[7]), float(m[8])))
        elif line.startswith('HFOLLOW '):
            m = re.match(r'HFOLLOW (\d+) task (\w+) .* at (\S+) (\S+) camera (\S+) (\S+) stopped (\d+) y (\S+) type (-?\d+)', line)
            if m:
                follow.setdefault(m[2], []).append((int(m[1]), float(m[3]), float(m[8]), float(m[4]), float(m[5]), float(m[6]), int(m[9])))
    for si, (f, ch, cx, cy, cz, lx, lz) in enumerate(stops):
        end = stops[si + 1][0] if si + 1 < len(stops) else 10**9
        ll = math.hypot(lx, lz) or 1.0
        lx, lz = lx / ll, lz / ll
        pts = []
        for task, s in follow.items():
            s = [p for p in s if f <= p[0] < end]
            if not s:
                continue
            x0, z0 = s[0][1], s[0][3]
            q = []
            for (fr, x, y, z, kx, kz, ty) in s:
                if math.hypot(kx - cx, kz - cz) > 25:   # (the camera left the stop)
                    break
                d = math.hypot(x - cx, z - cz)
                if math.hypot(x - x0, z - z0) < 8 or d < 30 or d > 120:
                    continue
                if ((x - cx) * lx + (z - cz) * lz) / d < 0.6:
                    continue
                q.append((x, y, z, ty))
            if q:
                pts.append(q[len(q) // 2])
        keep = []
        for p in sorted(pts, key=lambda p: math.hypot(p[0] - cx, p[2] - cz)):
            if all(math.hypot(p[0] - k[0], p[2] - k[2]) >= 15 for k in keep) and len(keep) < 4:
                keep.append(p)
        for (x, y, z, ty) in keep:
            rows.append((ch, cx, cz, lx, lz, x, y, z, ty))
with open(out, 'w', newline='\n') as o:
    o.write('// hordepub (generated by the worker\'s stands.py from plain-game traces, --strict --default-route, arcade models):\n')
    o.write('// {chapter, stop camera x, z, look x, z, x, y, z, type}: ground the arcade\'s own walkers walked at that stop\n')
    for r in rows:
        o.write('    {%d, %.1ff, %.1ff, %.3ff, %.3ff, %.1ff, %.1ff, %.1ff, %d},\n' % r)
print(len(rows), 'points', len({(r[0], r[1], r[2]) for r in rows}), 'stops')
